export function translate(language: LanguageCode, key: TranslationKey, params?: TranslationParams): string {
  let value: string = translations[language][key] ?? translations.en[key];
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? ''));
}

interface I18nContextValue {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (key: TranslationKey, params?: TranslationParams) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ language, setLanguage, children }: { language: LanguageCode; setLanguage: (language: LanguageCode) => void; children: React.ReactNode }) {
  const value = useMemo<I18nContextValue>(() => ({ language, setLanguage, t: (key, params) => translate(language, key, params) }), [language, setLanguage]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('I18nProvider is unavailable');
  return context;
}

